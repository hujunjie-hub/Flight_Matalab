function report=verify_rectime_time_mapping
%VERIFY_RECTIME_TIME_MAPPING Validate production UM982 RECTIMEA parsing and UTC mapping.
% The test uses a deterministic valid PPS edge stream and synthetic RECTIMEA
% bytes. It does not claim physical TIM2 capture or Host MIL UART integration.
root=flight_startup;
mexDirectory=fullfile(root,'work','mex');
assert(isfolder(mexDirectory),'Flight:RectimeMexDirectory', ...
    'Native MEX output directory is missing; run build_native_kernels first.');
addpath(mexDirectory);
assert(exist('fmt_rectime_time_probe','file')==3, ...
    'Flight:RectimeMexMissing','Run build_native_kernels to build fmt_rectime_time_probe.');

result=fmt_rectime_time_probe;
assert(isstruct(result) && isfield(result,'status') && ...
       isfield(result,'checks') && isfield(result,'failures') && ...
       isfield(result,'utc_mapping_epoch') && isfield(result,'utc_valid') && ...
       result.status==0 && result.failures==0 && result.checks>=20 && ...
       result.utc_mapping_epoch>0 && result.utc_valid==1, ...
    'Flight:RectimeTimeMappingRegression', ...
    'RECTIME parser/UTC mapping regression failed: %s',jsonencode(result));

tests={ ...
    'RECTIMEA_week_TOW_and_calendar_crosscheck', ...
    'GPS_to_UTC_leap_offset_crosscheck', ...
    'receiver_accuracy_and_output_delay_decoded', ...
    'CRC_corruption_rejected', ...
    'inconsistent_UTC_epoch_rejected', ...
    'latest_valid_PPS_capture_selected', ...
    'UTC_observation_paired_to_PPS_maps_UTC_domain', ...
    'stale_PPS_pair_rejected_without_destroying_locked_mapping'};

report=struct('scope','UM982_RECTIMEA_TO_UTC_MAPPING', ...
    'status','PASS','overall_P10_status','PARTIAL', ...
    'suite',result.suite,'checks',result.checks,'failures',result.failures, ...
    'utc_mapping_epoch',result.utc_mapping_epoch,'utc_valid',logical(result.utc_valid), ...
    'tests',{tests}, ...
    'source','Flight/middleware/protocol/unicore_ascii/unicore_ascii.c', ...
    'PPS_input','synthetic PpsCaptureEvent stream with deterministic local tick source', ...
    'not_validated','physical TIM2 capture ISR, UART DMA/interrupt delivery, Host MIL sensor_gnss_poll end-to-end execution');

file=fullfile(root,'work','validation','rectime_time_mapping_report.json');
if ~isfolder(fileparts(file)), mkdir(fileparts(file)); end
fid=fopen(file,'w');
assert(fid>=0,'Flight:RectimeReport','Could not create RECTIME mapping report.');
cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',jsonencode(report,PrettyPrint=true));
disp(report);
end
