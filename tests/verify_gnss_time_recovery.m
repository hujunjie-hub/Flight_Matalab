function report=verify_gnss_time_recovery
%VERIFY_GNSS_TIME_RECOVERY Run the upstream Flight GNSS/PPS/UTC loss tests.
% The test exercises production TimeService and GNSS sample-normalization
% sources with deterministic inputs; it does not claim raw RECTIME/UART or
% physical PPS capture integration in the Host MIL model.
root=flight_startup;
mexDirectory=fullfile(root,'work','mex');
assert(isfolder(mexDirectory),'Flight:GnssOutageMexDirectory', ...
    'Native MEX output directory is missing; run build_native_kernels first.');
addpath(mexDirectory);
assert(exist('fmt_gnss_outage_probe','file')==3, ...
    'Flight:GnssOutageMexMissing','Run build_native_kernels to build fmt_gnss_outage_probe.');

result=fmt_gnss_outage_probe;
assert(isstruct(result) && isfield(result,'status') && ...
       isfield(result,'checks') && isfield(result,'failures') && ...
       result.status==0 && result.failures==0 && result.checks>0, ...
    'Flight:GnssOutageRegression', ...
    'Upstream Flight GNSS/PPS/UTC recovery tests failed: %s',jsonencode(result));

tests={ ...
    'valid_PVT_and_no_fix_are_distinguished', ...
    'stale_GNSS_measurement_epoch_is_rejected', ...
    'navigation_loss_does_not_drop_healthy_PPS_UTC', ...
    'UTC_loss_with_PPS_enters_UTC_holdover', ...
    'PPS_loss_preserves_local_monotonic_clock_and_epoch', ...
    'PPS_reacquisition_requires_a_valid_interval_window', ...
    'UTC_mapping_recovers_without_changing_mapping_epoch', ...
    'bad_period_duplicate_and_overcapture_edges_are_rejected'};

report=struct('scope','UPSTREAM_FLIGHT_GNSS_TIME_RECOVERY', ...
    'status','PASS','overall_P10_status','PARTIAL', ...
    'upstream_suite',result.suite,'checks',result.checks, ...
    'failures',result.failures,'tests',{tests}, ...
    'sources',{{'Flight/sensor_device/time_base/systime.c', ...
        'Flight/middleware/sensor/sample_normalization/sensor_sample.c', ...
        'Flight/middleware/sensor/measurement_filter/sensor_filter.c', ...
        'Flight/middleware/sensor/calibration/sensor_calibration.c'}}, ...
    'not_validated','UM982 RECTIME byte parsing/arrival pairing inside MILSIM, physical TIM2 capture ISR and board timer hardware');

file=fullfile(root,'work','validation','gnss_time_recovery_report.json');
if ~isfolder(fileparts(file)), mkdir(fileparts(file)); end
fid=fopen(file,'w');
assert(fid>=0,'Flight:GnssOutageReport','Could not create GNSS recovery report.');
cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',jsonencode(report,PrettyPrint=true));
disp(report);
end
