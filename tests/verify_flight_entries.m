    bitand(uint32(s(:,6)),uint32(4)) == 0;
committedReceipt = s(:,7) == 1;
validM7Commit = controlPermitValid & committedReceipt & s(:,8) == 1;
firstPreArmRejectUs = 0;
firstHorizontalPositionUs = 0;
firstHorizontalVelocityUs = 0;
firstPrearmReadyUs = 0;
