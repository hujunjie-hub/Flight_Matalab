function report = verify_flight_entries(refreshRecording)
%VERIFY_FLIGHT_ENTRIES Execute closed loop and both replays against one tape.
if nargin == 0, refreshRecording = false; end
root = flight_startup;
mil = 'FMT_MILSIM';
commandTape = fmt_default_input(mil);
closed = run(mil,commandTape);
s = signal(closed,2);
force = signal(closed,1);
x = signal(closed,4);
fprintf('MIL max altitude %.3f m, final down %.3f m, final velocity %.3f m/s\n', ...
    max(-x(:,3)),x(end,3),norm(x(end,4:6)));
fprintf(['MIL diagnostics: armed=%d commit_valid=%d max_nav_mask=0x%02X ' ...
    'max_total_thrust=%.3f N max_motor_thrust=%.3f N last_request=%u ack=%u reason=%u\n'], ...
    any(s(:,3)==2),any(s(:,8)==1),uint32(max(s(:,12))), ...
    max(sum(force,2)),max(force(:)),s(end,9),s(end,10),s(end,11));

% Preserve each command's own ACK before a later command overwrites the
% single-current-request diagnostic fields in the runtime adapter.
requestIds=unique(s(:,9),'stable');
requestIds(requestIds==0)=[];
commandHistory=repmat(struct('time_us',0,'request_id',uint32(0), ...
    'command_code',uint16(0),'ack_state',uint16(0),'reason_code',uint16(0), ...
    'arm_state',uint8(0),'flight_mode',uint8(0),'failsafe_level',uint8(0), ...
    'prearm_state',uint16(0),'prearm_failed_mask',uint32(0), ...
    'prearm_primary_reason',uint16(0),'prearm_failed_count',uint16(0), ...
    'prearm_warning_count',uint16(0),'prearm_check_epoch',uint32(0), ...
    'authority',uint8(0),'mission_state',uint8(0), ...
    'origin_auth_attempts',uint32(0),'origin_auth_successes',uint32(0), ...
    'origin_auth_last_status',int32(0),'origin_reset_attempts',uint32(0), ...
    'origin_reset_successes',uint32(0),'origin_reset_last_status',int32(0), ...
    'origin_reset_last_type',uint16(0),'origin_reset_last_origin_id',uint32(0)),numel(requestIds),1);
fprintf('MIL command history (one final row per request):\n');
for k=1:numel(requestIds)
    rows=find(s(:,9)==requestIds(k));
    idx=rows(end);
    commandHistory(k)=struct('time_us',s(idx,1), ...
        'request_id',uint32(s(idx,9)),'command_code',uint16(s(idx,32)), ...
        'ack_state',uint16(s(idx,10)),'reason_code',uint16(s(idx,11)), ...
        'arm_state',uint8(s(idx,3)),'flight_mode',uint8(s(idx,4)), ...
        'failsafe_level',uint8(s(idx,5)),'prearm_state',uint16(s(idx,2)), ...
        'prearm_failed_mask',uint32(s(idx,25)), ...
        'prearm_primary_reason',uint16(s(idx,26)), ...
        'prearm_failed_count',uint16(s(idx,27)), ...
        'prearm_warning_count',uint16(s(idx,28)), ...
        'prearm_check_epoch',uint32(s(idx,29)), ...
        'authority',uint8(s(idx,30)),'mission_state',uint8(s(idx,31)), ...
        'origin_auth_attempts',uint32(s(idx,33)),'origin_auth_successes',uint32(s(idx,34)), ...
        'origin_auth_last_status',int32(s(idx,35)),'origin_reset_attempts',uint32(s(idx,36)), ...
        'origin_reset_successes',uint32(s(idx,37)),'origin_reset_last_status',int32(s(idx,38)), ...
        'origin_reset_last_type',uint16(s(idx,39)),'origin_reset_last_origin_id',uint32(s(idx,40)));
    fprintf(['  t=%.3f id=%u code=%u ack=%u reason=%u arm=%u mode=%u ' ...
        'failsafe=%u prearm=%u failed=0x%08X prearm_reason=%u failed_count=%u\n'], ...
        s(idx,1)/1e6,uint32(s(idx,9)),uint32(s(idx,32)), ...
        uint32(s(idx,10)),uint32(s(idx,11)),uint32(s(idx,3)), ...
        uint32(s(idx,4)),uint32(s(idx,5)),uint32(s(idx,2)), ...
        uint32(s(idx,25)),uint32(s(idx,26)),uint32(s(idx,27)));
end
horizontalPositionValid = bitand(uint32(s(:,12)),uint32(8)) ~= 0;
horizontalVelocityValid = bitand(uint32(s(:,12)),uint32(32)) ~= 0;
prearmReady = s(:,2) == 2;
firstHorizontalPositionUs = 0;
firstHorizontalVelocityUs = 0;
firstPrearmReadyUs = 0;
idx = find(horizontalPositionValid,1,'first');
if ~isempty(idx), firstHorizontalPositionUs = s(idx,1); end
idx = find(horizontalVelocityValid,1,'first');
if ~isempty(idx), firstHorizontalVelocityUs = s(idx,1); end
idx = find(prearmReady,1,'first');
if ~isempty(idx), firstPrearmReadyUs = s(idx,1); end
milDiagnostics=struct('scope','MIL_COMMAND_AND_PREARM_DIAGNOSTICS', ...
    'maximum_altitude_m',max(-x(:,3)),'final_down_m',x(end,3), ...
    'final_speed_mps',norm(x(end,4:6)),'maximum_navigation_mask',uint32(max(s(:,12))), ...
    'horizontal_position_valid_seen',any(horizontalPositionValid), ...
    'horizontal_velocity_valid_seen',any(horizontalVelocityValid), ...
    'prearm_ready_seen',any(prearmReady), ...
    'first_horizontal_position_time_us',firstHorizontalPositionUs, ...
    'first_horizontal_velocity_time_us',firstHorizontalVelocityUs, ...
    'first_prearm_ready_time_us',firstPrearmReadyUs, ...
    'origin_auth_attempts',uint32(max(s(:,33))),'origin_auth_successes',uint32(max(s(:,34))), ...
    'origin_auth_last_status',int32(s(end,35)),'origin_reset_attempts',uint32(max(s(:,36))), ...
    'origin_reset_successes',uint32(max(s(:,37))),'origin_reset_last_status',int32(s(end,38)), ...
    'origin_reset_last_type',uint16(s(end,39)),'origin_reset_last_origin_id',uint32(s(end,40)), ...
    'arm_seen',any(s(:,3)==2),'commit_seen',any(s(:,8)==1), ...
    'maximum_total_thrust_n',max(sum(force,2)), ...
    'final_prearm_state',uint16(s(end,2)), ...
    'final_prearm_failed_mask',uint32(s(end,25)), ...
    'final_prearm_primary_reason',uint16(s(end,26)), ...
    'final_prearm_failed_count',uint16(s(end,27)), ...
    'final_failsafe_level',uint8(s(end,5)), ...
    'command_history',commandHistory);
diagFile=fullfile(root,'work','validation','mil_diagnostics.json');
if ~isfolder(fileparts(diagFile)), mkdir(fileparts(diagFile)); end
diagFid=fopen(diagFile,'w');
assert(diagFid>=0,'Flight:MILDiagnostics','Could not write MIL diagnostics.');
diagCleanup=onCleanup(@()fclose(diagFid));
fprintf(diagFid,'%s\n',jsonencode(milDiagnostics,PrettyPrint=true));
clear diagCleanup;
assert(all(isfinite(x),'all') && all(isfinite(force),'all'),'Flight:MILFinite','Nonfinite closed-loop output.');
assert(any(horizontalPositionValid),'Flight:MILHorizontalPosition', ...
    'GNSS-assisted origin reset did not establish valid horizontal position.');
assert(any(s(:,34)>0),'Flight:OriginAuthorization','FMS did not authorize any GNSS origin reset.');
assert(any(s(:,37)>0),'Flight:OriginReset','INS did not successfully execute an authorized origin reset.');
assert(any(prearmReady),'Flight:MILPreArmReady', ...
    'FMS PreArm never reached PREARM_READY after navigation initialization.');
assert(any(s(:,3)==2),'Flight:MILArm','MIL never entered the armed state.');
assert(any(s(:,8)==1),'Flight:MILCommit','MIL never produced a valid actuator commit.');
assert(max(-x(:,3))>=1.8,'Flight:MILTakeoff', ...
    'MIL did not reach the required 1.8 m minimum takeoff altitude.');
assert(all(force(s(:,8)==0,:)==0,'all'),'Flight:Permit','Nonzero thrust without a current commit.');
assert(s(end,3)==0 && s(end,10)==3 && norm(x(end,4:6))<.15 && abs(x(end,3))<.1, ...
    'Flight:MILLanding','The simulated flight did not land and disarm.');
assert(all(s(:,24)==0),'Flight:FirmwareSIL','Flight host fixture checks failed.');

if refreshRecording
    t = closed.tout;
    sensor = signal(closed,5);
    commands = commandTape{1}.Data;
    navigation = signal(closed,3);
    % The core outputs at k+1 the result from step k. External M3 replay
    % must inject that result during step k, with its original contract time.
    navigation = navigation([2:end end],:);
    meta = fmt_flight_metadata;
    revision = meta.product_contract_revision;
    save(fullfile(root,'scenarios','flight_sil_recording.mat'), ...
        't','sensor','commands','navigation','revision','-v7');
end

data = run('FMT_DataSIM',fmt_default_input('FMT_DataSIM'));
ext = run('FMT_ExtINS_DataSIM',fmt_default_input('FMT_ExtINS_DataSIM'));
dataStatus = signal(data,2);
extStatus = signal(ext,2);
assert(isequaln(s,dataStatus) && isequaln(force,signal(data,1)), ...
    'Flight:SensorReplay','Replaying MIL sensors diverged from the closed-loop run.');
assert(isequaln(dataStatus(:,[3:8 12:18]),extStatus(:,[3:8 12:18])) && ...
    isequaln(signal(data,1),signal(ext,1)), ...
    'Flight:ExternalReplay','External navigation replay diverged from the recorded flight.');
assert(all(extStatus(:,24)==0),'Flight:ExternalSIL','Flight host fixture checks failed in ExtINS.');

% Invalid samples remain invalid and must not become actuator commands.
dropout = fmt_default_input('FMT_DataSIM');
bad = dropout{1}.Data;
bad(:,17) = 0;
dropout{1} = setinterpmethod(timeseries(bad,dropout{1}.Time),'zoh');
off = run('FMT_DataSIM',dropout,'4.2');
assert(all(signal(off,1)==0,'all'),'Flight:Dropout','Missing sensors permitted thrust.');

report = struct('status','PASS','duration_s',closed.tout(end), ...
    'maximum_altitude_m',max(-x(:,3)),'final_height_m',-x(end,3), ...
    'final_speed_mps',norm(x(end,4:6)),'mpc_updates',s(end,22), ...
    'actuator_commits',s(end,23),'sensor_replay_identical',true, ...
    'external_navigation_control_identical',true,'invalid_sensors_inhibit',true);
file = fopen(fullfile(root,'work','validation','flight_entries.json'),'w');
cleanup = onCleanup(@()fclose(file));
fprintf(file,'%s\n',jsonencode(report,PrettyPrint=true));
disp(report);
end

function out = run(model,ds,stop)
if nargin < 3, stop = '26'; end
input = Simulink.SimulationInput(model);
input = input.setExternalInput(ds);
input = input.setModelParameter('StopTime',stop);
out = sim(input);
assert(abs(out.tout(end)-str2double(stop))<1e-10,'Flight:EarlyStop','%s stopped early.',model);
end

function data = signal(out,port)
data = out.yout{port}.Values.Data;
end


