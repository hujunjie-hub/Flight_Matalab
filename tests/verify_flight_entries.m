firstOriginAuthSuccessUs = 0;
firstOriginResetSuccessUs = 0;
idx = find(s(:,34)>0,1,'first');
if ~isempty(idx), firstOriginAuthSuccessUs = s(idx,1); end
idx = find(s(:,37)>0,1,'first');
if ~isempty(idx), firstOriginResetSuccessUs = s(idx,1); end
idx = find(horizontalPositionValid,1,'first');
if ~isempty(idx), firstHorizontalPositionUs = s(idx,1); end
idx = find(horizontalVelocityValid,1,'first');
if ~isempty(idx), firstHorizontalVelocityUs = s(idx,1); end
idx = find(prearmReady,1,'first');
if ~isempty(idx), firstPrearmReadyUs = s(idx,1); end
milDiagnostics=struct('scope','MIL_COMMAND_AND_PREARM_DIAGNOSTICS', ...
    'maximum_altitude_m',max(-x(:,3)),'final_down_m',x(end,3), ...
