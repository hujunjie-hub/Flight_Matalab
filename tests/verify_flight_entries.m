    'horizontal_velocity_valid_seen',any(horizontalVelocityValid), ...
    'prearm_reject_seen',any(prearmReject),'prearm_ready_seen',any(prearmReady), ...
    'first_prearm_reject_time_us',firstPreArmRejectUs, ...
    'first_origin_auth_success_time_us',firstOriginAuthSuccessUs, ...
    'first_origin_reset_success_time_us',firstOriginResetSuccessUs, ...
    'first_horizontal_position_time_us',firstHorizontalPositionUs, ...
    'first_horizontal_velocity_time_us',firstHorizontalVelocityUs, ...
    'first_prearm_ready_time_us',firstPrearmReadyUs, ...
    'origin_auth_attempts',uint32(max(s(:,33))),'origin_auth_successes',uint32(max(s(:,34))), ...
    'origin_auth_last_status',int32(s(end,35)),'origin_reset_attempts',uint32(max(s(:,36))), ...
    'origin_reset_successes',uint32(max(s(:,37))),'origin_reset_last_status',int32(s(end,38)), ...
    'origin_reset_last_type',uint16(s(end,39)),'origin_reset_last_origin_id',uint32(s(end,40)), ...
    'gnss_submit_attempts',uint32(max(s(:,41))),'gnss_submit_successes',uint32(max(s(:,42))), ...
    'gnss_submit_last_status',int32(s(end,43)),'gnss_push_attempts',uint32(max(s(:,44))), ...
    'gnss_push_successes',uint32(max(s(:,45))),'gnss_push_last_status',int32(s(end,46)), ...
    'origin_poll_attempts',uint32(max(s(:,47))),'origin_poll_successes',uint32(max(s(:,48))), ...
    'origin_poll_last_status',int32(s(end,49)),'origin_poll_last_sequence',uint32(s(end,50)), ...
    'origin_poll_last_next_id',uint32(s(end,51)),'sensor_turn_count',uint32(max(s(:,52))), ...
    'mission_turn_count',uint32(max(s(:,53))),'origin_wake_count',uint32(max(s(:,54))), ...
    'candidate_observed_count',uint32(max(s(:,55))),'candidate_last_sequence',uint32(s(end,56)), ...
    'candidate_last_sample_us',uint64(s(end,57)),'candidate_last_valid_until_us',uint64(s(end,58)), ...
    'candidate_last_next_id',uint32(s(end,59)),'candidate_last_age_us',uint64(s(end,60)), ...
    'mil_gnss_gate_released',any(s(:,61)==1), ...
    'mil_gnss_gate_ready_time_us',uint64(s(end,62)), ...
    'mil_gnss_gate_wait_steps',uint32(max(s(:,63))), ...
    'mil_gnss_first_fix_sequence',uint32(s(end,64)), ...
    'mil_gnss_first_fix_sample_us',uint64(s(end,65)), ...
    'gnss_push_not_ready_count',uint32(max(s(:,66))), ...
    'gnss_push_not_permitted_count',uint32(max(s(:,67))), ...
    'gnss_push_other_failures',uint32(max(s(:,68))), ...
    'origin_snapshot_status',int32(s(end,69)), ...
    'origin_valid_mask_seen',uint32(max(s(:,70))), ...
    'final_origin_valid_mask',uint32(s(end,70)), ...
    'final_origin_id',uint32(s(end,71)), ...
    'candidate_first_sequence',uint32(s(end,72)), ...
    'candidate_first_sample_us',uint64(s(end,73)), ...
    'candidate_first_age_us',uint64(s(end,74)), ...
    'first_terminal_time_us',uint64(s(end,75)), ...
    'first_terminal_decision_code',uint32(s(end,76)), ...
    'first_terminal_decision_reason',uint32(s(end,77)), ...
    'first_terminal_landed_state',uint32(s(end,78)), ...
    'first_terminal_landed_stable_ms',uint32(s(end,79)), ...
    'first_terminal_landed_evidence',uint32(s(end,80)), ...
    'first_terminal_landed_confidence',s(end,81), ...
    'first_terminal_control_health_state',uint32(s(end,82)), ...
    'first_terminal_control_dof_mask',uint32(s(end,83)), ...
    'first_terminal_control_degraded_dof_mask',uint32(s(end,84)), ...
    'first_terminal_control_reason',uint32(s(end,85)), ...
    'first_terminal_control_status',int32(s(end,86)), ...
    'first_terminal_runtime_control_health',uint32(s(end,87)), ...
    'first_terminal_solver_status',uint32(s(end,88)), ...
    'first_terminal_deadline_miss_count',uint32(s(end,89)), ...
    'first_terminal_allocation_failure_count',uint32(s(end,90)), ...
    'first_terminal_actuator_fault_mask',uint32(s(end,91)), ...
    'first_terminal_actuator_available_mask',uint32(s(end,92)), ...
    'first_terminal_actuator_cap_available_mask',uint32(s(end,93)), ...
    'first_terminal_actuator_cap_dof_mask',uint32(s(end,94)), ...
    'first_terminal_permit_flags',uint32(s(end,95)), ...
    'first_terminal_permit_reason',uint32(s(end,96)), ...
    'first_terminal_guidance_state',uint32(s(end,97)), ...
    'first_terminal_guidance_reason',uint32(s(end,98)), ...
    'first_terminal_guidance_feasible',uint32(s(end,99)), ...
    'first_terminal_feasibility_reason',uint32(s(end,100)), ...
    'first_terminal_control_reference_id',uint32(s(end,101)), ...
    'first_terminal_receipt_result_code',uint32(s(end,102)), ...
    'first_terminal_runtime_error',int32(s(end,103)), ...
    'first_terminal_mpc_updates',uint32(s(end,104)), ...
    'first_terminal_nav_capability_mask',uint32(s(end,105)), ...
    'first_terminal_nav_solution_state',uint32(s(end,106)), ...
    'first_terminal_nav_valid_mask',uint32(s(end,107)), ...
    'first_terminal_bundle_ready',uint32(s(end,108)), ...
    'arm_prearm_state_at_submit',uint16(s(end,109)), ...
    'arm_prearm_failed_mask_at_submit',uint32(s(end,110)), ...
    'arm_prearm_epoch_at_submit',uint32(s(end,111)), ...
    'arm_submit_time_us',uint64(s(end,112)), ...
    'arm_request_id',uint32(s(end,113)), ...
    'control_permit_seen',any(controlPermitValid), ...
    'committed_receipt_seen',any(committedReceipt), ...
    'valid_m7_commit_seen',any(validM7Commit), ...
    'arm_seen',any(s(:,3)==2),'commit_seen',any(s(:,8)==1), ...
    'maximum_total_thrust_n',max(sum(force,2)), ...
    'final_prearm_state',uint16(s(end,2)), ...
    'final_prearm_failed_mask',uint32(s(end,25)), ...
    'final_prearm_primary_reason',uint16(s(end,26)), ...
    'final_prearm_failed_count',uint16(s(end,27)), ...
    'final_failsafe_level',uint8(s(end,5)), ...
    'command_history',commandHistory);
diagFile=fullfile(root,'work','validation','mil_diagnostics.json');
if ~isfolder(fileparts(diagFile)), mkdir(fileparts(diagFile)); end
diagFid=fopen(diagFile,'w');
assert(diagFid>=0,'Flight:MILDiagnostics','Could not write MIL diagnostics.');
diagCleanup=onCleanup(@()fclose(diagFid));
fprintf(diagFid,'%s\n',jsonencode(milDiagnostics,PrettyPrint=true));
clear diagCleanup;
assert(all(isfinite(x),'all') && all(isfinite(force),'all'),'Flight:MILFinite','Nonfinite closed-loop output.');
assert(any(s(:,41)>0),'Flight:MILGNSSInjection','No GNSS measurement was submitted by the deterministic sensor simulator.');
assert(any(s(:,44)>0),'Flight:MILGNSSIngestion','GNSS measurements never reached the estimator ingestion API.');
assert(any(s(:,47)>0),'Flight:MILOriginPoll','Sensor task never polled the pending-origin API.');
assert(any(s(:,61)==1),'Flight:MILGNSSGate','MIL GNSS was not released after INS attitude initialization.');
assert(any(s(:,70)==1),'Flight:MILOriginPlaceholder','MIL did not start from a provisional local-only origin.');
assert(any(s(:,70)==3),'Flight:MILOriginRebuild','GNSS Origin Reset did not promote the origin to a complete valid origin.');
assert(s(end,71)>1,'Flight:MILOriginID','Origin ID did not advance after FMS-authorized reset.');
assert(s(end,69)==0,'Flight:MILOriginSnapshot','INS origin snapshot was not readable at the end of MIL.');
assert(any(s(:,66)>0),'Flight:MILGNSSStaged','No GNSS sample was staged as a late first fix.');
assert(s(end,63)>0 && s(end,64)>1 && s(end,65)>=s(end,62), ...
    'Flight:MILLateGNSS','First GNSS fix was not delayed until after INS initialization.');
assert(s(end,72)==s(end,64) && s(end,73)==s(end,65) && s(end,74)<20000, ...
    'Flight:MILOriginCandidateIdentity','Origin Candidate did not preserve the first GNSS fix identity/freshness.');
assert(s(end,68)==0,'Flight:MILGNSSPushErrors','Unexpected GNSS estimator ingestion errors occurred.');
assert(any(horizontalPositionValid),'Flight:MILHorizontalPosition', ...
    'GNSS-assisted origin reset did not establish valid horizontal position.');
assert(any(s(:,34)>0),'Flight:OriginAuthorization','FMS did not authorize any GNSS origin reset.');
assert(any(s(:,37)>0),'Flight:OriginReset','INS did not successfully execute an authorized origin reset.');
assert(any(s(:,37)>0 & s(:,39)==2 & s(:,40)>0),'Flight:OriginResetIdentity', ...
    'Successful INS reset was not an ORIGIN_REBUILD for a nonzero origin ID.');
assert(any(prearmReject) && any(prearmReady) && firstPreArmRejectUs<firstPrearmReadyUs, ...
    'Flight:PreArmTransition','PreArm did not transition from REJECT to READY.');
assert(firstOriginAuthSuccessUs>0 && firstOriginResetSuccessUs>=firstOriginAuthSuccessUs && ...
    firstHorizontalPositionUs>=firstOriginResetSuccessUs, ...
    'Flight:OriginResetOrder','Origin authorization, INS reset and horizontal position were not observed in order.');
armCommand=find([commandHistory.command_code]==1,1,'first');
assert(~isempty(armCommand) && commandHistory(armCommand).ack_state==3 && ...
    s(end,109)==2 && s(end,110)==0 && s(end,111)>0 && ...
    s(end,112)>0 && s(end,113)==commandHistory(armCommand).request_id, ...
    'Flight:ArmPreArmSnapshot', ...
    'ARM completion did not bind to a READY, zero-failure PreArm snapshot at request submission.');
assert(s(end,75)==0,'Flight:MILTerminalFailsafe', ...
    sprintf(['Terminal failsafe at %.3f s: decision=%u reason=%u landed=%u stable_ms=%u ' ...
    'control_health=%u dof=0x%X control_reason=0x%X actuator_fault=0x%X ' ...
    'actuator_available=0x%X permit_reason=%u guidance=%u/%u nav_cap=0x%X.'], ...
    s(end,75)/1e6,uint32(s(end,76)),uint32(s(end,77)),uint32(s(end,78)), ...
    uint32(s(end,79)),uint32(s(end,82)),uint32(s(end,83)),uint32(s(end,85)), ...
    uint32(s(end,91)),uint32(s(end,92)),uint32(s(end,96)), ...
    uint32(s(end,97)),uint32(s(end,98)),uint32(s(end,105))));
assert(any(prearmReady),'Flight:MILPreArmReady', ...
    'FMS PreArm never reached PREARM_READY after navigation initialization.');
assert(any(s(:,3)==2),'Flight:MILArm','MIL never entered the armed state.');
assert(any(validM7Commit),'Flight:MILCommit', ...
    'No current CONTROL_ACTIVE permit and COMMITTED M7 receipt were observed together.');
assert(max(-x(:,3))>=1.8,'Flight:MILTakeoff', ...
    'MIL did not reach the required 1.8 m minimum takeoff altitude.');
assert(all(force(s(:,8)==0,:)==0,'all'),'Flight:Permit','Nonzero thrust without a current commit.');
assert(s(end,3)==0 && s(end,10)==3 && norm(x(end,4:6))<.15 && abs(x(end,3))<.1, ...
    'Flight:MILLanding','The simulated flight did not land and disarm.');
assert(all(s(:,24)==0),'Flight:FirmwareSIL','Flight host fixture checks failed.');

if refreshRecording
    t = closed.tout;
    sensor = signal(closed,5);
    commands = commandTape{1}.Data;
    navigation = signal(closed,3);
    % The core outputs at k+1 the result from step k. External M3 replay
    % must inject that result during step k, with its original contract time.
    navigation = navigation([2:end end],:);
    meta = fmt_flight_metadata;
    revision = meta.product_contract_revision;
    save(fullfile(root,'scenarios','flight_sil_recording.mat'), ...
        't','sensor','commands','navigation','revision','-v7');
end

data = run('FMT_DataSIM',fmt_default_input('FMT_DataSIM'));
ext = run('FMT_ExtINS_DataSIM',fmt_default_input('FMT_ExtINS_DataSIM'));
dataStatus = signal(data,2);
extStatus = signal(ext,2);
assert(isequaln(s,dataStatus) && isequaln(force,signal(data,1)), ...
    'Flight:SensorReplay','Replaying MIL sensors diverged from the closed-loop run.');
dataMotors = signal(data,1);
extMotors = signal(ext,1);
navCols = [3:8 12:18];
if ~(isequaln(dataStatus(:,navCols),extStatus(:,navCols)) && isequaln(dataMotors,extMotors))
    a = dataStatus(:,navCols); b = extStatus(:,navCols);
    sameCells = (a==b) | (isnan(a)&isnan(b));
    row = find(~all(sameCells,2),1,'first');
    if isempty(row)
        sameMotor = (dataMotors==extMotors) | (isnan(dataMotors)&isnan(extMotors));
        row = find(~all(sameMotor,2),1,'first');
    end
    if isempty(row), row = 1; end
    diffCols = false(1,numel(navCols));
    for k = 1:numel(navCols)
        diffCols(k) = ~isequaln(dataStatus(:,navCols(k)),extStatus(:,navCols(k)));
    end
    fprintf('ExternalReplay first divergence: row=%d t=%.4f s cols=[%s]\n', ...
        row, s(row,1)*1e-6, num2str(navCols(diffCols)));
    for k = find(diffCols)
        fprintf('  col %d: data=%.6g ext=%.6g\n', navCols(k), dataStatus(row,navCols(k)), extStatus(row,navCols(k)));
    end
    sameMotor = (dataMotors==extMotors) | (isnan(dataMotors)&isnan(extMotors));
    motorRow = find(~all(sameMotor,2),1,'first');
    if ~isempty(motorRow)
        fprintf('  motors first differ row=%d t=%.4f s data=[%s] ext=[%s]\n', motorRow, ...
            s(motorRow,1)*1e-6, num2str(dataMotors(motorRow,:)), num2str(extMotors(motorRow,:)));
