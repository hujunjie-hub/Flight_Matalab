function report=verify_parameter_view
%VERIFY_PARAMETER_VIEW Check generated values against Flight-owned source data.
root=flight_startup;
cfg=generate_parameters;
runtime=fileread(fullfile(root,'..','Flight','applications','runtime','runtime.c'));
token=regexp(runtime,'out->guidance\.payload\.gravity_mps2\s*=\s*([0-9.]+)f','tokens','once');
assert(~isempty(token),'Flight:GravitySource','Flight runtime gravity assignment was not found.');
expectedGravity=str2double(token{1});
assert(cfg.derived.GravityMps2==expectedGravity,'Flight:SharedGravity', ...
    'Plant gravity differs from Flight Host SIL.');
assert(isequal(size(cfg.derived.EstimatorP0),[22 22]) && ...
       isequal(size(cfg.derived.EstimatorQc),[19 19]), ...
    'Flight:NoiseShape','Wrong covariance/noise dimensions.');
assert(abs(cfg.derived.EstimatorQc(1,1)-4e-7)<1e-18 && ...
       abs(cfg.derived.EstimatorQc(4,4)-1e-9)<1e-18 && ...
       abs(cfg.derived.EstimatorQc(19,19)-1e-4)<1e-18, ...
    'Flight:NoiseUnits','STD to PSD conversion failed.');
assert(abs(cfg.derived.EstimatorP0(10,10)-1e-6)<1e-18 && ...
       abs(cfg.derived.EstimatorQc(7,7)-2e-8/3600)<1e-20, ...
    'Flight:NoiseSeparation','Initial and stationary bias STD were mixed.');

position=cfg.vehicle_model.motor_position_frd_m';
yaw=cfg.vehicle_model.motor_yaw_torque_ratio_m(:)';
expectedWrench=[zeros(2,4);-ones(1,4);-position(2,:);position(1,:);yaw];
assert(max(abs(cfg.derived.WrenchMatrix(:)-expectedWrench(:)))<1e-12, ...
    'Flight:WrenchMatrix','Plant wrench matrix differs from Flight motor geometry.');
expectedEffectiveness=[ones(1,4);expectedWrench(4:6,:)];
assert(max(abs(cfg.derived.AllocationEffectiveness(:)-expectedEffectiveness(:)))<1e-12, ...
    'Flight:AllocationEffectiveness','Allocation effectiveness differs from Flight.');
assert(max(abs(cfg.derived.AllocationEffectiveness * ...
    cfg.derived.AllocationInverse-eye(4)),[],'all')<1e-10, ...
    'Flight:AllocationInverse','Generated allocation inverse is inconsistent.');
assert(isequal(size(cfg.derived.AllocationMatrices),[8 4]), ...
    'Flight:AllocationShape','Expected the 8x4 S-Function allocation parameter.');
assert(max(abs(cfg.derived.AllocationMatrices(1:4,:)- ...
    cfg.derived.AllocationInverse),[],'all')<1e-12 && ...
    max(abs(cfg.derived.AllocationMatrices(5:8,:)- ...
    cfg.derived.AllocationEffectiveness),[],'all')<1e-12, ...
    'Flight:AllocationPacking','Allocation parameter packing is invalid.');

J=reshape(cfg.vehicle_model.inertia_frd_kgm2,3,3);
assert(max(abs(J-J'),[],'all')<1e-12 && all(eig(J)>0), ...
    'Flight:InertiaSPD','Plant inertia must be symmetric positive definite.');
assert(numel(cfg.derived.PlantParameters)==26 && ...
       norm(reshape(cfg.derived.PlantParameters(2:10),3,3)-J,'fro')<1e-12, ...
    'Flight:PlantParameterShape','Plant parameter vector must preserve the full 3x3 inertia tensor.');
assert(abs(cfg.derived.PlantParameters(26)-cfg.vehicle_model.ground_friction)<1e-12, ...
    'Flight:GroundFriction','Plant ground friction parameter is not preserved.');
assert(numel(cfg.derived.MotorMinN)==4 && numel(cfg.derived.MotorMaxN)==4, ...
    'Flight:MotorLimits','Four motor limits must be present in the parameter view.');
assert(isequal(cfg.derived.MagneticFieldNedUt, ...
    cfg.sensor_alignment.magnetic_field_ned_ut(:)), ...
    'Flight:MagneticField','Plant magnetic field differs from SIM_ONLY alignment.');
origin=cfg.vehicle_model.origin_llh_rad_m(:);
earthRate=cfg.derived.EarthRotationRadps*[cos(origin(1));0;-sin(origin(1))];
assert(max(abs(cfg.derived.EarthRateNedRadps-earthRate))<1e-14, ...
    'Flight:EarthRate','Fixed-N0 Earth rate is inconsistent with the SIM origin.');
sensor=cfg.sensor_alignment;
expectedSensorParameters=[cfg.derived.GravityMps2;cfg.derived.MagneticFieldNedUt(:); ...
    cfg.derived.EarthRateNedRadps(:);cfg.derived.PlantState0(4:6); ...
    cfg.derived.PlantState0(11:13);sensor.imu_to_cg_frd_m(:); ...
    sensor.antenna_from_imu_frd_m(:)];
assert(numel(cfg.derived.SensorParameters)==19 && ...
       max(abs(cfg.derived.SensorParameters(:)-expectedSensorParameters))<1e-12, ...
    'Flight:SensorParameterView','SensorParameters must preserve Earth terms and both configured lever arms.');
expectedSensorModelParameters=[sensor.random_seed;sensor.imu_installation(:); ...
    sensor.mag_installation(:);sensor.static_gyro_bias_radps(:); ...
    sensor.static_accel_bias_mps2(:);sensor.static_mag_bias_ut(:); ...
    sensor.scale_error(:);sensor.scale_error(:);sensor.scale_error(:); ...
    sensor.gyro_noise_std_radps(:);sensor.accel_noise_std_mps2(:); ...
    sensor.mag_noise_std_ut(:);sensor.gnss_position_noise_std_m(:); ...
    sensor.gnss_velocity_noise_std_mps(:);sensor.baro_noise_std_m; sensor.baro_bias_m];
assert(numel(cfg.derived.SensorModelParameters)==54 && ...
       max(abs(cfg.derived.SensorModelParameters(:)-expectedSensorModelParameters))<1e-12, ...
    'Flight:SensorModelParameterView', ...
    'SensorModelParameters must preserve seed, installation, residual calibration and noise STD.');
expectedSensorTimingParameters=[sensor.imu_sample_period_us;sensor.mag_sample_period_us; ...
    sensor.baro_sample_period_us;sensor.gnss_sample_period_us; ...
    sensor.imu_pipeline_delay_us;sensor.imu_transport_delay_us; ...
    sensor.mag_transport_delay_us;sensor.baro_transport_delay_us; ...
    sensor.gnss_transport_delay_us;sensor.imu_pipeline_uncertainty_us];
assert(numel(cfg.derived.SensorTimingParameters)==10 && ...
       max(abs(cfg.derived.SensorTimingParameters(:)-expectedSensorTimingParameters))<1e-12, ...
    'Flight:SensorTimingParameterView', ...
    'SensorTimingParameters must preserve sample periods, delays and timing uncertainty.');

report=struct('scope','GENERATED_PARAMETER_VIEW','status','PASS', ...
    'shared_flight_runtime_gravity','PASS','P0_22_Qc_19','PASS', ...
    'white_STD_to_PSD','PASS','initial_and_stationary_STD_separate','PASS', ...
    'flight_motor_geometry_and_yaw','PASS','generic_allocation_inverse','PASS', ...
    'full_inertia_3x3_preserved','PASS','plant_parameter_schema_26','PASS', ...
    'P18_full_inertia_parameter_contract','PASS', ...
    'sensor_magnetic_field_alignment','PASS','fixed_N0_earth_rate','PASS', ...
    'sensor_parameter_schema_19','PASS','imu_and_antenna_levers_preserved','PASS', ...
    'sensor_model_parameter_schema_54','PASS','sensor_seed_and_noise_parameters','PASS', ...
    'sensor_timing_parameter_schema_10','PASS');
fid=fopen(fullfile(root,'work','validation','parameter_view_report.json'),'w');
cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',jsonencode(report,PrettyPrint=true));
disp(report);
end
