function report=verify_time_service_sync
%VERIFY_TIME_SERVICE_SYNC Run the upstream Flight PPS/UTC TimeService tests.
% This is a core-level regression gate. PPS edges are supplied as synthetic
% PpsCaptureEvent records by the upstream test fixture; it does not claim
% physical TIM2 capture or UART/RECTIME end-to-end MIL integration.
root=flight_startup;
mexDirectory=fullfile(root,'work','mex');
assert(isfolder(mexDirectory),'Flight:TimeServiceMexDirectory', ...
    'Native MEX output directory is missing; run build_native_kernels first.');
addpath(mexDirectory);
assert(exist('fmt_time_service_probe','file')==3, ...
    'Flight:TimeServiceMexMissing','Run build_native_kernels to build fmt_time_service_probe.');

result=fmt_time_service_probe;
assert(isstruct(result) && isfield(result,'status') && ...
       isfield(result,'checks') && isfield(result,'failures') && ...
       result.status==0 && result.failures==0 && result.checks>0, ...
    'Flight:TimeServiceRegression', ...
    'Upstream Flight TimeService tests failed: %s',jsonencode(result));

tests={ ...
    'monotonic_tick_to_FCU_mapping', ...
    'PPS_period_gate_and_frequency_lock', ...
    'PPS_sequence_and_holdover_behavior', ...
    'UTC_observation_requires_PPS_pairing', ...
    'UTC_mapping_uncertainty_and_degradation', ...
    'external_clock_domain_mapping', ...
    'time_epoch_discontinuity_rejection'};

report=struct('scope','UPSTREAM_FLIGHT_TIME_SERVICE_CORE', ...
    'status','PASS','overall_P10_status','PARTIAL', ...
    'upstream_suite',result.suite,'checks',result.checks, ...
    'failures',result.failures,'tests',{tests}, ...
    'PPS_input','synthetic PpsCaptureEvent with deterministic tick source', ...
    'UTC_input','paired GnssTimeObservation', ...
    'validated','PPS sequence/period gates, local frequency discipline, UTC mapping, pairing, uncertainty, holdover and epoch rejection', ...
    'not_validated','physical TIM2 capture ISR, UM982 UART RECTIME parsing inside MILSIM, board clock hardware');

file=fullfile(root,'work','validation','time_service_sync_report.json');
if ~isfolder(fileparts(file)), mkdir(fileparts(file)); end
fid=fopen(file,'w');
assert(fid>=0,'Flight:TimeServiceReport','Could not create TimeService report.');
cleanup=onCleanup(@()fclose(fid));
fprintf(fid,'%s\n',jsonencode(report,PrettyPrint=true));
disp(report);
end
