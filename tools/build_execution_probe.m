function build_execution_probe(startStage)
%BUILD_EXECUTION_PROBE Prove ordered function calls through Model Reference.
% This G1 fixture is deliberately separate from the functional entry models.
root = fileparts(fileparts(mfilename('fullpath')));
if nargin<1, startStage=1; end
folder = fullfile(root,'tests','g1','models');
if ~isfolder(folder),mkdir(folder);end
addpath(folder);
worker = 'FMT_G1_OrderedWorker';
core = 'FMT_G1_ExecutionCore';
if startStage<=1
newmodel(worker,folder);
ids = fmt_edit(worker,'root',{
    config(worker,'SingleTasking',true), ...
    struct('op','configure','target',['config:' worker],'params',struct('SetExecutionDomain','on','ExecutionDomainType','ExportFunction')), ...
    block('Inport','Invoke','call',struct('Port','1','OutputFunctionCall','on','SampleTime','-1')), ...
    block('Inport','PreviousOrdinal','prev',struct('Port','2','OutDataTypeStr','uint64')), ...
    block('Inport','ExpectedOrdinal','expected',struct('Port','3','OutDataTypeStr','uint64')), ...
    block('Outport','Ordinal','out',struct('Port','1')), ...
    block('Outport','Count','count',struct('Port','2')), ...
    struct('op','create_subsystem','name','OnInvoke','ref','body', ...
      'interface',struct('inputs',{{'PreviousOrdinal','ExpectedOrdinal'}},'outputs',{{'Ordinal','Count'}}))});
body = ids.body;
readout = char(model_read(worker,body,'0'));
inIds = regexp(readout,'id: (blk_\d+) #u\d','tokens');
outIds = regexp(readout,'id: (blk_\d+) #y\d','tokens');
assert(numel(inIds)==2 && numel(outIds)==2,'Flight:ProbeInterface','Unexpected subsystem interface.');
fmt_edit(worker,body,{
    block('TriggerPort','Invoke','invoke',struct('TriggerType','function-call')), ...
    block('Constant','One','one',struct('Value','uint64(1)','OutDataTypeStr','uint64')), ...
    block('Sum','NextOrdinal','next',struct('Inputs','++','OutDataTypeStr','uint64')), ...
    block('RelationalOperator','IsOrdered','ordered',struct('Operator','==')), ...
    block('Assertion','CheckOrder','assert',struct), ...
    block('UnitDelay','CallCounter','reg',struct('InitialCondition','uint64(0)','SampleTime','-1')), ...
    block('Sum','IncrementCount','inc',struct('Inputs','++','OutDataTypeStr','uint64')), ...
    wire([inIds{1}{1} '.y1'],'#next.u1'),wire('#one.y1','#next.u2'), ...
    wire('#next.y1',[outIds{1}{1} '.u1']), ...
    wire([inIds{1}{1} '.y1'],'#ordered.u1'),wire([inIds{2}{1} '.y1'],'#ordered.u2'), ...
    wire('#ordered.y1','#assert.u1'),wire('#reg.y1','#inc.u1'),wire('#one.y1','#inc.u2'), ...
    wire('#inc.y1','#reg.u1'),wire('#inc.y1',[outIds{2}{1} '.u1'])});
fmt_edit(worker,'root',{
    wire([ids.call '.y1'],[body '.trigger']),wire([ids.prev '.y1'],[body '.u1']), ...
    wire([ids.expected '.y1'],[body '.u2']),wire([body '.y1'],[ids.out '.u1']), ...
    wire([body '.y2'],[ids.count '.u1'])},'incremental');
verify(worker);
save_system(worker);
end

if startStage<=2
newmodel(core,folder);
ids = fmt_edit(core,'root',{config(core,'SingleTasking',true), ...
    block('Chart','SimTickCoordinator','scheduler',struct), ...
    block('Mux','PhaseCounts','mux',struct('Inputs','11')), ...
    block('Outport','PhaseCountOutput','out',struct('Port','1')), ...
    block('Outport','GlobalTick','tick',struct('Port','2')), ...
    block('Outport','RateSlotCounts','slots',struct('Port','3'))});
chart = ids.scheduler;
ops = {struct('op','configure','target',['chart:' core], ...
    'params',struct('ActionLanguage','MATLAB','ChartUpdate','DISCRETE','SampleTime','0.0005')), ...
    sfdata('tick','Input','uint64','1','0'),sfdata('slots','Output','uint64','[8 1]','0'), ...
    sfdata('stop_ticks','Parameter','uint64','1','0')};
phases = {'A_TimeApply','B_Sample','C_ReleaseGuard','D_Estimator', ...
    'E_FMS','F_Guidance','G_MpcJob','H_Control','I_Frame','J_LogStop','K_PlantStep'};
for k=1:11
    ops{end+1}=struct('op','add_block','type','Event','ref',sprintf('ev%d',k), ...
        'params',struct('Name',phases{k},'Scope','Output','Trigger','Function call'));
end
calls = strjoin(cellfun(@(s)[s '();'],phases,UniformOutput=false),' ');
body = sprintf(['if tick < stop_ticks\n' ...
    'slots(1)=slots(1)+uint64(1);\n' ...
    'if rem(tick,uint64(2))==0, slots(2)=slots(2)+uint64(1); end\n' ...
    'if rem(tick,uint64(5))==0, slots(3)=slots(3)+uint64(1); end\n' ...
    'if rem(tick,uint64(20))==0, slots(4)=slots(4)+uint64(1); end\n' ...
    'if rem(tick,uint64(40))==0, slots(5)=slots(5)+uint64(1); end\n' ...
    'if rem(tick,uint64(200))==0, slots(6)=slots(6)+uint64(1); end\n' ...
    'if rem(tick,uint64(2000))==0, slots(7)=slots(7)+uint64(1); slots(8)=slots(8)+uint64(1); end\n' ...
    '%s\nend'],calls);
label = sprintf('RUN\nen: slots=zeros(8,1,\x27uint64\x27);\n%s\ndu:\n%s',body,body);
ops{end+1}=struct('op','add_block','type','State','name','RUN','ref','run','params',struct('LabelString',label));
ops{end+1}=struct('op','connect','target','? -> #run');
fmt_edit(core,chart,ops);
disp(model_check(core,chart,'["stateflow_lint"]'));
ops={block('UnitDelay','GlobalTickRegister','clock',struct('InitialCondition','uint64(0)','SampleTime','0.0005')), ...
    block('Constant','TickIncrement','tickone',struct('Value','uint64(1)','OutDataTypeStr','uint64')), ...
    block('Sum','NextGlobalTick','ticknext',struct('Inputs','++','OutDataTypeStr','uint64')), ...
    wire('#clock.y1','#ticknext.u1'),wire('#tickone.y1','#ticknext.u2'),wire('#ticknext.y1','#clock.u1'), ...
    wire('#clock.y1',[chart '.u1']),wire('#clock.y1',[ids.tick '.u1']),wire([chart '.y1'],[ids.slots '.u1']), ...
    wire([ids.mux '.y1'],[ids.out '.u1']), ...
    block('Gain','TickOrdinal','seed',struct('Gain','uint64(11)','OutDataTypeStr','uint64')), ...
    wire('#clock.y1','#seed.u1')};
for k=1:11
    ref=sprintf('phase%d',k);
    ops{end+1}=block('ModelReference',phases{k},ref,struct('ModelName',worker,'SimulationMode','Normal'));
    ops{end+1}=block('Bias',sprintf('Expected%d',k),sprintf('ex%d',k), ...
        struct('Bias',sprintf('uint64(%d)',k-1)));
    ops{end+1}=wire('#seed.y1',sprintf('#ex%d.u1',k));
    ops{end+1}=wire(sprintf('#ex%d.y1',k),['#' ref '.u3']);
    ops{end+1}=wire(sprintf('%s.y%d',chart,k+1),['#' ref '.u1']);
    if k==1, prev='#seed.y1'; else, prev=sprintf('#phase%d.y1',k-1); end
    ops{end+1}=wire(prev,['#' ref '.u2']);
    ops{end+1}=wire(['#' ref '.y2'],sprintf('%s.u%d',ids.mux,k));
end
ops{end+1}=block('Terminator','FinalOrdinal','end',struct);
ops{end+1}=wire('#phase11.y1','#end.u1');
fmt_edit(core,'root',ops,'incremental');
workspace=get_param(core,'ModelWorkspace');
assignin(workspace,'stop_ticks',uint64(4000));
verify(core);
save_system(core);
end

for model={'FMT_G1_DataSIM','FMT_G1_MILSIM','FMT_G1_ExtINS_DataSIM'}
    name=model{1}; newmodel(name,folder);
    fmt_edit(name,'root',{config(name,'SingleTasking',true), ...
        block('ModelReference','SharedExecutionCore','core',struct('ModelName',core,'SimulationMode','Normal')), ...
        block('Outport','PhaseCounts','counts',struct('Port','1')), ...
        block('Outport','GlobalTick','tick',struct('Port','2')), ...
        block('Outport','RateSlotCounts','slots',struct('Port','3')), ...
        wire('#core.y1','#counts.u1'),wire('#core.y2','#tick.u1'),wire('#core.y3','#slots.u1')});
    verify(name); save_system(name);
end
fprintf('G1 topology models generated; functional M1-M7 implementation is separate.\n');
end

function newmodel(name,folder)
if bdIsLoaded(name), error('Flight:AlreadyOpen','Refusing to replace loaded model %s.',name); end
file=fullfile(folder,[name '.slx']);
assert(~isfile(file),'Flight:AlreadyExists','Refusing to overwrite %s.',file);
new_system(name); open_system(name); save_system(name,file);
end

function op=config(name,~,~)
op=struct('op','configure','target',['config:' name],'params',struct( ...
    'SolverType','Fixed-step','Solver','FixedStepDiscrete','FixedStep','0.0005', ...
    'EnableMultiTasking','off','StopTime','2','ReturnWorkspaceOutputs','on', ...
    'SaveOutput','on','SaveFormat','Dataset','ModelReferenceNumInstancesAllowed','Multi', ...
    'Description','G1 EXECUTION TOPOLOGY PROOF ONLY. No flight algorithms; not a completed FlightSIM entry.'));
end

function op=block(type,name,ref,params)
op=struct('op','add_block','type',type,'name',name,'ref',ref,'params',params);
end

function op=wire(source,destination)
op=struct('op','connect','target',[source ' -> ' destination]);
end

function op=sfdata(name,scope,type,size,initial)
params=containers.Map({'Name','Scope','DataType','Props.Array.Size','Props.InitialValue'}, ...
    {name,scope,type,size,initial});
op=struct('op','add_block','type','Data','ref',name,'params',params);
end

function verify(model)
result=char(model_check(model,'root','["all"]'));
assert(contains(result,'status: healthy'),'Flight:Structure','%s',result);
disp(model_read(model,'root','0'));
end
