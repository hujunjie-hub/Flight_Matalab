function register_flight_entries
%REGISTER_FLIGHT_ENTRIES Register the firmware-backed artifacts in the MATLAB project.
root = fileparts(fileparts(mfilename('fullpath')));
project = openProject(fullfile(root,'Flight_Matalab.prj'));
addPath(project,fullfile(root,'models','flight'));
files = {'config/firmware_sources.json','config/flight_baseline.json', ...
    'adapters/flight_runtime/fmt_flight_runtime.h','adapters/flight_runtime/fmt_flight_runtime.c', ...
    'adapters/flight_runtime/fmt_flight_sfun.c','adapters/flight_runtime/fmt_plant_sensors_sfun.c', ...
    'models/flight/FMT_FlightCore.slx','simulation/FMT_DataSIM.slx','simulation/FMT_MILSIM.slx', ...
    'simulation/FMT_ExtINS_DataSIM.slx','scenarios/flight_sil_recording.mat', ...
    'tools/build_flight_runtime.ps1','tools/record_flight_baseline.py','tools/build_flight_mex.m', ...
    'tools/build_flight_models.m','tools/fmt_default_input.m','tools/fmt_flight_metadata.m', ...
    'tools/fmt_flight_nav_width.m','tools/register_flight_entries.m','tests/verify_flight_entries.m'};
for k = 1:numel(files)
    file = fullfile(root,files{k});
    assert(isfile(file),'Flight:ProjectArtifact','Missing project artifact %s.',file);
    if isempty(findFile(project,file)), addFile(project,file); end
end
fprintf('Registered Flight firmware entries and their recording in %s.\n',project.Name);
end
