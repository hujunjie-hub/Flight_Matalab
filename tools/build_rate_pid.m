function build_rate_pid(model,scope)
%BUILD_RATE_PID Native Read/Evaluate/Backcalculate/conditional Commit graph.
root=fileparts(fileparts(mfilename('fullpath')));
if nargin==0
    model='FMT_RatePIDTransaction';scope='root';
    assert(~bdIsLoaded(model)&&~isfile(fullfile(root,'models','core',[model '.slx'])),'Flight:Exists','PID already exists.');
    new_system(model);open_system(model);save_system(model,fullfile(root,'models','core',[model '.slx']));
end
ops={struct('op','configure','target',['config:' model],'params',struct( ...
    'SolverType','Fixed-step','Solver','FixedStepDiscrete','FixedStep','auto','EnableMultiTasking','off', ...
    'DataDictionary','Flight_Parameters.sldd', ...
    'SaveFormat','Dataset','ReturnWorkspaceOutputs','on','StopTime','2', ...
    'Description','Rate PID numerical transaction component. Time/context contract guard belongs to M6; not the complete M6 controller.'))};
if ~strcmp(scope,'root'),ops={};end
names={'OmegaDesired','OmegaMeasured','ActualDtS','NumericTransaction','ResetTransaction','TransactionValidated','AllocationResidualNm'};
width=[3 3 1 1 1 1 3];types={'double','double','double','boolean','boolean','boolean','double'};
for k=1:7
    ops{end+1}=b('Inport',names{k},sprintf('u%d',k),struct('Port',num2str(k),'PortDimensions',num2str(width(k)),'OutDataTypeStr',types{k}));
end
outs={'RequestedTorqueNm','IntegralStateNm','DerivativeState','NumericCommitCount'};
for k=1:4,ops{end+1}=b('Outport',outs{k},sprintf('y%d',k),struct('Port',num2str(k)));end
ops=[ops,{
    b('UnitDelay','IntegralRegister','I',struct('InitialCondition','[0;0;0]','SampleTime','-1')), ...
    b('UnitDelay','DerivativeRegister','D',struct('InitialCondition','[0;0;0]','SampleTime','-1')), ...
    b('UnitDelay','MeasurementRegister','omega',struct('InitialCondition','[0;0;0]','SampleTime','-1')), ...
    b('Constant','ZeroVector','zero',struct('Value','[0;0;0]')),b('Constant','One','one',struct('Value','1')), ...
    b('Constant','MinimumEvaluationDt','dtmin',struct('Value','1e-6')), ...
    b('MinMax','SafeEvaluationDt','dt',struct('Function','max','Inputs','2')), ...
    b('Sum','RateError','error',struct('Inputs','+-')),b('Gain','ProportionalTorque','P',struct('Gain','RateKp')), ...
    b('Switch','ResetIntegralView','iview',sw),b('Switch','ResetDerivativeView','dview',sw), ...
    b('Sum','MeasurementDifference','delta',struct('Inputs','+-')), ...
    b('Product','MeasurementDerivative','derivative',struct('Inputs','*/')), ...
    b('Gain','NegativeCutoffRad','cutoff',struct('Gain','-2*pi*RateDcutoff')), ...
    b('Math','DerivativeAlpha','alpha',struct('Operator','exp')), ...
    b('Sum','OneMinusAlpha','beta',struct('Inputs','+-')), ...
    b('Product','RetainedDerivative','retained',struct('Inputs','**')), ...
    b('Product','NewDerivativeWeight','fresh',struct('Inputs','**')), ...
    b('Sum','DerivativeCandidate','dcandidate',struct('Inputs','++')), ...
    b('Switch','ContextDerivativeView','deval',sw), ...
    b('Gain','DerivativeTorque','Kd',struct('Gain','RateKd')), ...
    b('Sum','TorqueUsingCurrentI','tau',struct('Inputs','++-')), ...
    b('Gain','IntegralErrorRate','Ki',struct('Gain','RateKi')), ...
    b('Gain','CurrentResidualFeedback','Kaw',struct('Gain','RateKaw')), ...
    b('Sum','IntegralDerivative','idot',struct('Inputs','++')), ...
    b('Product','IntegralIncrement','idelta',struct('Inputs','**')), ...
    b('Sum','IntegralCandidate','icandidate',struct('Inputs','++')), ...
    b('Saturate','IntegralLimits','clip',struct('UpperLimit','RateIlimit','LowerLimit','-RateIlimit')), ...
    b('Logic','ValidatedNumeric','commit',struct('Operator','AND','Inputs','2')), ...
    b('Logic','NotReset','notreset',struct('Operator','NOT')), ...
    b('Logic','CommitEnable','enable',struct('Operator','AND','Inputs','2')), ...
    b('Logic','NumericEvaluation','evaluate',struct('Operator','AND','Inputs','2')), ...
    b('Switch','CommitIntegral','icommit',sw),b('Switch','InstallIntegralReset','inext',sw), ...
    b('Switch','CommitDerivative','dcommit',sw),b('Switch','InstallDerivativeReset','dnext',sw), ...
    b('Switch','CommitMeasurement','omegacommit',sw),b('Switch','InstallMeasurementSeed','omeganext',sw), ...
    b('UnitDelay','CommitCountRegister','count',struct('InitialCondition','uint32(0)','SampleTime','-1')), ...
    b('Constant','CountOne','countone',struct('Value','uint32(1)','OutDataTypeStr','uint32')), ...
    b('Sum','NextCommitCount','countinc',struct('Inputs','++','OutDataTypeStr','uint32')), ...
    b('Switch','CommitCountEnable','countnext',sw), ...
    w('#u1.y1','#error.u1'),w('#u2.y1','#error.u2'),w('#error.y1','#P.u1'), ...
    w('#u3.y1','#dt.u1'),w('#dtmin.y1','#dt.u2'), ...
    w('#zero.y1','#iview.u1'),w('#u5.y1','#iview.u2'),w('#I.y1','#iview.u3'), ...
    w('#zero.y1','#dview.u1'),w('#u5.y1','#dview.u2'),w('#D.y1','#dview.u3'), ...
    w('#u2.y1','#delta.u1'),w('#omega.y1','#delta.u2'),w('#delta.y1','#derivative.u1'),w('#dt.y1','#derivative.u2'), ...
    w('#dt.y1','#cutoff.u1'),w('#cutoff.y1','#alpha.u1'),w('#one.y1','#beta.u1'),w('#alpha.y1','#beta.u2'), ...
    w('#alpha.y1','#retained.u1'),w('#dview.y1','#retained.u2'), ...
    w('#beta.y1','#fresh.u1'),w('#derivative.y1','#fresh.u2'),w('#retained.y1','#dcandidate.u1'),w('#fresh.y1','#dcandidate.u2'), ...
    w('#dcandidate.y1','#deval.u1'),w('#evaluate.y1','#deval.u2'),w('#dview.y1','#deval.u3'),w('#deval.y1','#Kd.u1'), ...
    w('#P.y1','#tau.u1'),w('#iview.y1','#tau.u2'),w('#Kd.y1','#tau.u3'),w('#tau.y1','#y1.u1'), ...
    w('#I.y1','#y2.u1'),w('#D.y1','#y3.u1'), ...
    w('#error.y1','#Ki.u1'),w('#u7.y1','#Kaw.u1'),w('#Ki.y1','#idot.u1'),w('#Kaw.y1','#idot.u2'), ...
    w('#idot.y1','#idelta.u1'),w('#u3.y1','#idelta.u2'),w('#iview.y1','#icandidate.u1'),w('#idelta.y1','#icandidate.u2'),w('#icandidate.y1','#clip.u1'), ...
    w('#u4.y1','#commit.u1'),w('#u6.y1','#commit.u2'),w('#u5.y1','#notreset.u1'),w('#commit.y1','#enable.u1'),w('#notreset.y1','#enable.u2'), ...
    w('#u4.y1','#evaluate.u1'),w('#notreset.y1','#evaluate.u2'), ...
    w('#clip.y1','#icommit.u1'),w('#enable.y1','#icommit.u2'),w('#I.y1','#icommit.u3'), ...
    w('#zero.y1','#inext.u1'),w('#u5.y1','#inext.u2'),w('#icommit.y1','#inext.u3'),w('#inext.y1','#I.u1'), ...
    w('#deval.y1','#dcommit.u1'),w('#enable.y1','#dcommit.u2'),w('#D.y1','#dcommit.u3'), ...
    w('#zero.y1','#dnext.u1'),w('#u5.y1','#dnext.u2'),w('#dcommit.y1','#dnext.u3'),w('#dnext.y1','#D.u1'), ...
    w('#u2.y1','#omegacommit.u1'),w('#enable.y1','#omegacommit.u2'),w('#omega.y1','#omegacommit.u3'), ...
    w('#u2.y1','#omeganext.u1'),w('#u5.y1','#omeganext.u2'),w('#omegacommit.y1','#omeganext.u3'),w('#omeganext.y1','#omega.u1'), ...
    w('#count.y1','#countinc.u1'),w('#countone.y1','#countinc.u2'),w('#countinc.y1','#countnext.u1'), ...
    w('#enable.y1','#countnext.u2'),w('#count.y1','#countnext.u3'),w('#countnext.y1','#count.u1'),w('#count.y1','#y4.u1')}];
fmt_edit(model,scope,ops);
result=char(model_check(model,scope,'["all"]'));assert(contains(result,'status: healthy'),'Flight:PIDStructure','%s',result);
save_system(model);
end

function params=sw
params=struct('Criteria','u2 ~= 0');
end
function op=b(type,name,ref,params)
op=struct('op','add_block','type',type,'name',name,'ref',ref,'params',params);
end
function op=w(source,destination)
op=struct('op','connect','target',[source ' -> ' destination]);
end
