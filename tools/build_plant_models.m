function build_plant_models(startStage)
%BUILD_PLANT_MODELS Construct visible motor, wrench, RHS and RK4 model graphs.
root=fileparts(fileparts(mfilename('fullpath')));
folder=fullfile(root,'models','plant');
if nargin<1, startStage=1; end

if startStage<=1
model='FMT_RotorWrench';
% A previously inspected blank MATLAB Function is replaced by a native Gain.
if bdIsLoaded(model)
    fmt_edit(model,'root',{struct('op','delete','target','blk_1')},'incremental');
else
    make(model,folder);
end
fmt_edit(model,'root',{
    settings(model),port('Inport','RotorForceN','f',1,4),port('Outport','BodyWrench','out',1,6), ...
    block('Gain','GeometryCrossProducts','map',struct('Gain','WrenchMatrix','Multiplication','Matrix(K*u)')), ...
    wire('#f.y1','#map.u1'),wire('#map.y1','#out.u1')});
finish(model);
end

if startStage<=2
model='FMT_MotorRHS';make(model,folder);
fmt_edit(model,'root',{
    settings(model),port('Inport','MotorOmega','omega',1,4),port('Inport','TargetForceN','force',2,4), ...
    port('Outport','OmegaDerivative','out',1,4),port('Outport','RotorForceN','actual',2,4), ...
    block('Saturate','TargetRange','sat',struct('UpperLimit','MotorMaxN','LowerLimit','MotorMinN')), ...
    block('Gain','ForceToOmegaSquared','inverse',struct('Gain','1/MotorKf')), ...
    block('Sqrt','TargetOmega','sqrt',struct), ...
    block('Sum','OmegaError','error',struct('Inputs','+-')), ...
    block('Gain','InverseMotorTimeConstant','tau',struct('Gain','1/MotorTau')), ...
    block('Product','OmegaSquared','square',struct('Inputs','**')), ...
    block('Gain','ThrustCoefficient','kf',struct('Gain','MotorKf')), ...
    wire('#force.y1','#sat.u1'),wire('#sat.y1','#inverse.u1'),wire('#inverse.y1','#sqrt.u1'), ...
    wire('#sqrt.y1','#error.u1'),wire('#omega.y1','#error.u2'),wire('#error.y1','#tau.u1'), ...
    wire('#tau.y1','#out.u1'),wire('#omega.y1','#square.u1'),wire('#omega.y1','#square.u2'), ...
    wire('#square.y1','#kf.u1'),wire('#kf.y1','#actual.u1')});
finish(model);
end

if startStage<=3
model='FMT_GroundRHS';make(model,folder);
fmt_edit(model,'root',{
    settings(model),port('Inport','PlantState','x',1,17),port('Inport','Environment','env',2,15), ...
    port('Outport','BodyWrench','out',1,6),port('Outport','SignedGapM','gap',2,1), ...
    port('Outport','NormalForceN','fn',3,1), ...
    block('S-Function','GeometricContactKernel','kernel',struct('Parameters','PlantParameters','FunctionName','fmt_ground_sfun')), ...
    wire('#x.y1','#kernel.u1'),wire('#env.y1','#kernel.u2'),wire('#kernel.y1','#out.u1'), ...
    wire('#kernel.y2','#gap.u1'),wire('#kernel.y3','#fn.u1')});
finish(model);
end

if startStage<=4
model='FMT_RigidBodyRHS';make(model,folder);
fmt_edit(model,'root',{
    settings(model),port('Inport','PlantState','x',1,17),port('Inport','RotorWrench','rotor',2,6), ...
    port('Inport','GroundWrench','ground',3,6),port('Inport','Environment','env',4,15), ...
    port('Outport','RigidDerivative','out',1,13), ...
    block('S-Function','NewtonEulerQuaternionKernel','kernel',struct('Parameters','PlantParameters','FunctionName','fmt_rigid_sfun')), ...
    wire('#x.y1','#kernel.u1'),wire('#rotor.y1','#kernel.u2'),wire('#ground.y1','#kernel.u3'), ...
    wire('#env.y1','#kernel.u4'),wire('#kernel.y1','#out.u1')});
finish(model);
end

if startStage<=5
model='FMT_PlantRHS';make(model,folder);
fmt_edit(model,'root',{
    settings(model),port('Inport','PlantState','x',1,17),port('Inport','AppliedForceN','u',2,4), ...
    port('Inport','Environment','env',3,15),port('Outport','Derivative','dx',1,17), ...
    port('Outport','NormalForceN','fn',2,1),port('Outport','SignedGapM','gap',3,1), ...
    block('Demux','ExtractMotorState','motorstate',struct('Outputs','[13 4]')), ...
    block('Demux','ExtractEffectiveness','effect',struct('Outputs','[11 4]')), ...
    block('Terminator','RigidStateBranch','unusedx',struct),block('Terminator','EnvironmentBranch','unusedenv',struct), ...
    reference('MotorDynamics','motor','FMT_MotorRHS'),reference('RotorWrench','rotor','FMT_RotorWrench'), ...
    reference('GroundContact','ground','FMT_GroundRHS'),reference('RigidBody','rigid','FMT_RigidBodyRHS'), ...
    block('Product','PhysicalEffectiveness','loe',struct('Inputs','**')), ...
    block('Mux','Assemble17Derivatives','mux',struct('Inputs','2')), ...
    wire('#x.y1','#motorstate.u1'),wire('#motorstate.y1','#unusedx.u1'),wire('#motorstate.y2','#motor.u1'), ...
    wire('#env.y1','#effect.u1'),wire('#effect.y1','#unusedenv.u1'),wire('#effect.y2','#loe.u2'), ...
    wire('#u.y1','#motor.u2'),wire('#motor.y2','#loe.u1'),wire('#loe.y1','#rotor.u1'), ...
    wire('#x.y1','#ground.u1'),wire('#env.y1','#ground.u2'), ...
    wire('#x.y1','#rigid.u1'),wire('#rotor.y1','#rigid.u2'),wire('#ground.y1','#rigid.u3'), ...
    wire('#env.y1','#rigid.u4'),wire('#rigid.y1','#mux.u1'),wire('#motor.y1','#mux.u2'), ...
    wire('#mux.y1','#dx.u1'),wire('#ground.y3','#fn.u1'),wire('#ground.y2','#gap.u1')});
finish(model);
end

if startStage<=6
model='FMT_QuadPlantStep';make(model,folder);
ops={settings(model),port('Inport','PlantState','x',1,17),port('Inport','AppliedForceN','u',2,4), ...
    port('Inport','Environment','env',3,15),port('Outport','NextState','out',1,17), ...
    port('Outport','QuaternionNormBefore','norm',2,1),port('Outport','NormalForceN','fn',3,1), ...
    port('Outport','SignedGapM','gap',4,1)};
for k=1:4
    ref=sprintf('k%d',k);
    ops{end+1}=reference(sprintf('RK4_PureRHS%d',k),ref,'FMT_PlantRHS');
    ops{end+1}=wire('#u.y1',['#' ref '.u2']);ops{end+1}=wire('#env.y1',['#' ref '.u3']);
    if k==1
        ops{end+1}=wire('#x.y1','#k1.u1');
        ops{end+1}=wire('#k1.y2','#fn.u1');ops{end+1}=wire('#k1.y3','#gap.u1');
    else
        if k<4, gain='PlantStepS/2'; else, gain='PlantStepS'; end
        ops{end+1}=block('Gain',sprintf('Stage%dDelta',k),sprintf('h%d',k),struct('Gain',gain));
        ops{end+1}=block('Sum',sprintf('Stage%dState',k),sprintf('x%d',k),struct('Inputs','++'));
        ops{end+1}=wire(sprintf('#k%d.y1',k-1),sprintf('#h%d.u1',k));
        ops{end+1}=wire(sprintf('#h%d.y1',k),sprintf('#x%d.u2',k));
        ops{end+1}=wire('#x.y1',sprintf('#x%d.u1',k));
        ops{end+1}=wire(sprintf('#x%d.y1',k),['#' ref '.u1']);
        for j=2:3
            term=sprintf('unused%d%d',k,j);
            ops{end+1}=block('Terminator',sprintf('Stage%dDiagnostic%d',k,j),term,struct);
            ops{end+1}=wire(sprintf('#k%d.y%d',k,j),['#' term '.u1']);
        end
    end
end
ops=[ops,{block('Gain','DoubleK2','twok2',struct('Gain','2')),block('Gain','DoubleK3','twok3',struct('Gain','2')), ...
    block('Sum','RK4WeightedSum','weighted',struct('Inputs','++++')), ...
    block('Gain','StepOverSix','scale',struct('Gain','PlantStepS/6')), ...
    block('Sum','UnnormalizedNextState','next',struct('Inputs','++')), ...
    block('S-Function','NormalizeQuaternionOnce','normalize',struct('FunctionName','fmt_normalize_sfun')), ...
    wire('#k2.y1','#twok2.u1'),wire('#k3.y1','#twok3.u1'), ...
    wire('#k1.y1','#weighted.u1'),wire('#twok2.y1','#weighted.u2'), ...
    wire('#twok3.y1','#weighted.u3'),wire('#k4.y1','#weighted.u4'), ...
    wire('#weighted.y1','#scale.u1'),wire('#scale.y1','#next.u2'),wire('#x.y1','#next.u1'), ...
    wire('#next.y1','#normalize.u1'),wire('#normalize.y1','#out.u1'),wire('#normalize.y2','#norm.u1')}];
fmt_edit(model,'root',ops);finish(model);
end

if startStage<=7
model='FMT_QuadPlant';make(model,folder);
fmt_edit(model,'root',{
    settings(model),port('Inport','AppliedForceN','u',1,4),port('Inport','Environment','env',2,15), ...
    port('Outport','PlantState','out',1,17),port('Outport','NormalForceN','fn',2,1), ...
    port('Outport','SignedGapM','gap',3,1),port('Outport','QuaternionNormBefore','norm',4,1), ...
    block('UnitDelay','PlantStateRegister','state',struct('InitialCondition','PlantState0','SampleTime','PlantStepS')), ...
    reference('ExplicitRK4Step','step','FMT_QuadPlantStep'),wire('#state.y1','#step.u1'), ...
    wire('#u.y1','#step.u2'),wire('#env.y1','#step.u3'),wire('#step.y1','#state.u1'), ...
    wire('#state.y1','#out.u1'),wire('#step.y2','#norm.u1'),wire('#step.y3','#fn.u1'),wire('#step.y4','#gap.u1')});
finish(model);
end
end

function make(model,folder)
assert(~bdIsLoaded(model)&&~isfile(fullfile(folder,[model '.slx'])),'Flight:Exists','Refusing to replace %s.',model);
new_system(model);open_system(model);save_system(model,fullfile(folder,[model '.slx']));
end

function finish(model)
result=char(model_check(model,'root','["all"]'));
assert(contains(result,'status: healthy'),'Flight:PlantStructure','%s',result);
save_system(model);fprintf('Saved %s (structurally connected).\n',model);
end

function op=settings(model)
op=struct('op','configure','target',['config:' model],'params',struct( ...
    'SolverType','Fixed-step','Solver','FixedStepDiscrete','FixedStep','0.0005', ...
    'EnableMultiTasking','off','StopTime','2','ReturnWorkspaceOutputs','on', ...
    'SaveOutput','on','SaveFormat','Dataset','ModelReferenceNumInstancesAllowed','Multi', ...
    'DataDictionary','Flight_Parameters.sldd','Description','SIM_ONLY physical component. System flight acceptance is separate.'));
end

function op=port(type,name,ref,num,width)
params=struct('Port',num2str(num));
if strcmp(type,'Inport'),params.PortDimensions=num2str(width);params.OutDataTypeStr='double'; end
op=block(type,name,ref,params);
end

function op=reference(name,ref,model)
op=block('ModelReference',name,ref,struct('ModelName',model,'SimulationMode','Normal'));
end

function op=block(type,name,ref,params)
op=struct('op','add_block','type',type,'name',name,'ref',ref,'params',params);
end

function op=wire(source,destination)
op=struct('op','connect','target',[source ' -> ' destination]);
end
